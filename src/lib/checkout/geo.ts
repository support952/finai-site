export function regionsFor(country: string): Record<string, string> | null {
  if (country === "US") return US_STATES;
  if (country === "CA") return CA_PROVINCES;
  return null;
}

const POSTCODE: Record<string, RegExp> = {
  US: /^\d{5}(-\d{4})?$/,
  CA: /^[A-Za-z]\d[A-Za-z][ -]?\d[A-Za-z]\d$/,
  GB: /^[A-Za-z]{1,2}\d[A-Za-z\d]? ?\d[A-Za-z]{2}$/,
  AU: /^\d{4}$/,
  DE: /^\d{5}$/,
  FR: /^\d{5}$/,
};

export function isValidPostcode(country: string, zip: string): boolean {
  const re = POSTCODE[country];
  if (re) return re.test(zip.trim());
  return /^[A-Za-z0-9][A-Za-z0-9 -]{1,18}[A-Za-z0-9]$/.test(zip.trim());
}
